def main() -> int:
    root = ROOT
    seen: dict[str, list[str]] = {}
    # 1) 已有目标
    tgt = yaml.safe_load((root / "targets/top_companies.yaml").read_text(encoding="utf-8")) or {}
    for sec, names in (tgt.get("sectors") or {}).items():
        for n in names:
            seen.setdefault(n, []).append(f"sector:{sec}")
    # 2) 行业常识表
    for n in NATIONAL_EXTRA:
        if "national" not in seen.setdefault(n, []):
            seen[n].append("national")
    # 3) 省级表（带省名）
    prov: dict[str, list[str]] = {}
    for p, names in REGIONAL.items():
        prov[p] = []
        for n in names:
            seen.setdefault(n, []).append(f"prov:{p}")
            prov[p].append(n)

    out = {
        "generated_on": "2026-10-27",
        "note": ("全国知名企业 + 各省各地知名企业候选名单。用于衡量覆盖率："
                 "scripts/coverage_report.py 把这里的公司与 sources/ 对照。"
                 "名单是「值得覆盖」的目标，不代表都能合规覆盖；抓不到的进 blocked.jsonl。"),
        "national": sorted(seen),
        "by_province": {p: sorted(set(v)) for p, v in prov.items()},
    }
    dst = root / "targets/mega_companies.yaml"
    dst.write_text(yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=200),
                   encoding="utf-8")
    print(f"总候选 {len(seen)} 家；省级 {len(prov)} 个，覆盖 {sum(len(v) for v in prov.values())} 条（含重复）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
